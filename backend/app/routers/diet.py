router = APIRouter(prefix="/diet", tags=["diet"])
log = logging.getLogger("fitai.diet")


def _out(p: DietPlan) -> dict:
    return {"id": p.id, "title": p.title, "plan_date": p.plan_date.isoformat() if p.plan_date else None,
            "targets": p.targets, "preferences": p.preferences, "meals": p.meals, "totals": ns.plan_totals(p.meals),
            "generated_by": p.generated_by, "coach_note": p.coach_note, "is_saved": p.is_saved,
            "created_at": p.created_at.isoformat() + "Z"}


def _own(db: Session, user: User, pid: int) -> DietPlan:
    p = db.get(DietPlan, pid)
    if not p or p.user_id != user.id:
        raise HTTPException(404, "Diet plan not found")
    return p


@router.post("/generate", status_code=201)
def generate(body: DietPlanIn, user: User = Depends(ai_rate_limit), db: Session = Depends(get_db)):
    prof = user.profile
    if prof is None:
        raise HTTPException(409, "Complete onboarding first")
    calc = fitness_service.profile_targets(prof)
    cal = body.calorie_target or calc["calories"]["calorie_target"]
    macros = fitness_service.calculate_macros(cal, prof.current_weight_kg, prof.goal, prof.height_cm)
    targets = {"calorie_target": cal, "protein_g": body.protein_g or macros["protein_g"],
               "carbs_g": body.carbs_g or macros["carbs_g"], "fat_g": body.fat_g or macros["fat_g"]}
    diet = body.diet_preference or prof.diet_preference
    restrictions = body.food_restrictions if body.food_restrictions is not None else prof.food_restrictions
    prefs = {"diet": diet if diet != "custom" else (prof.custom_diet or "custom"), "restrictions": restrictions,
             "budget": body.budget, "preferences": body.food_preferences, "meals_per_day": body.meals_per_day}
    meals, generated_by, note, notice = None, "reference_engine", None, None
    provider = get_provider(user.ai_provider_pref)
    if body.use_ai and provider.is_real_llm:
        try:
            system, prompt = meal_plan_prompt(prof, targets, prefs, ns.SLOTS[body.meals_per_day])
            data = json.loads(provider.generate_json(system, prompt))
            meals = ns.finalize_ai_meals(data.get("meals") or [], body.meals_per_day)
            raw_note = data.get("coach_note")
            note = raw_note.strip()[:1000] if isinstance(raw_note, str) and raw_note.strip() else None
            generated_by = f"llm:{provider.label}"[:100]
        except (ProviderError, ValueError, json.JSONDecodeError, TypeError, AttributeError) as e:
            log.warning("AI meal plan failed, using reference engine: %s", e)
            notice = "AI planner unavailable; generated with the FitAI reference engine instead."
    elif body.use_ai:
        notice = "Demo mode: generated by the FitAI reference engine (no LLM configured)."
    if meals is None:
        engine_diet = diet if diet != "custom" else "non_vegetarian"
        meals = ns.generate_reference_plan(targets, engine_diet, restrictions, body.meals_per_day, body.budget,
                                           body.food_preferences or "")
        if not meals:
            raise HTTPException(422, "No meals match these dietary settings. Try relaxing a restriction.")
        tot = ns.plan_totals(meals)
        note = (f"Built from templates matched to your {diet.replace('_', '-')} preference and scaled to ~{cal} kcal. "
                f"This plan provides about {tot['protein_g']:.0f} g protein vs your {targets['protein_g']} g target — "
                "swap items or regenerate meals to fine-tune.")
    plan = DietPlan(user_id=user.id, title=f"{prefs['diet'].replace('_', ' ').title()[:120]} plan · {cal} kcal",
                    plan_date=date.today(), targets=targets, preferences=prefs, meals=meals,
                    generated_by=generated_by, coach_note=note, is_saved=False)
    db.add(plan)
    db.commit()
    return {**_out(plan), "notice": notice}


@router.get("/plans")
def list_plans(saved_only: bool = False, user: User = Depends(require_profile), db: Session = Depends(get_db)):
    q = select(DietPlan).where(DietPlan.user_id == user.id)
    if saved_only:
        q = q.where(DietPlan.is_saved.is_(True))
    return [_out(p) for p in db.scalars(q.order_by(DietPlan.id.desc()).limit(30))]


@router.get("/plans/latest")
def latest(user: User = Depends(require_profile), db: Session = Depends(get_db)):
    p = db.scalar(select(DietPlan).where(DietPlan.user_id == user.id).order_by(DietPlan.id.desc()))
    return _out(p) if p else None


@router.get("/plans/{pid}")
def get_plan(pid: int, user: User = Depends(require_profile), db: Session = Depends(get_db)):
    return _out(_own(db, user, pid))


@router.post("/plans/{pid}/save")
def save_plan(pid: int, user: User = Depends(require_profile), db: Session = Depends(get_db)):
    p = _own(db, user, pid)
    p.is_saved = True
    db.commit()
    return _out(p)


@router.delete("/plans/{pid}", status_code=204)
def delete_plan(pid: int, user: User = Depends(require_profile), db: Session = Depends(get_db)):
    db.delete(_own(db, user, pid))
    db.commit()


def _engine_diet(p: DietPlan, user: User) -> tuple[str, list]:
    d = user.profile.diet_preference
    return (d if d != "custom" else "non_vegetarian"), p.preferences.get("restrictions", user.profile.food_restrictions)


@router.post("/plans/{pid}/regenerate-meal")
def regenerate_meal(pid: int, body: RegenerateMealIn, user: User = Depends(require_profile), db: Session = Depends(get_db)):
    p = _own(db, user, pid)
    diet, restr = _engine_diet(p, user)
    p.meals = ns.regenerate_meal(copy.deepcopy(p.meals), body.slot, p.targets, diet, restr, p.preferences.get("budget", "medium"))
    flag_modified(p, "meals")
    db.commit()
    return _out(p)


@router.post("/plans/{pid}/replace-item")
def replace_item(pid: int, body: ReplaceItemIn, user: User = Depends(require_profile), db: Session = Depends(get_db)):
    p = _own(db, user, pid)
    diet, restr = _engine_diet(p, user)
    p.meals = ns.replace_item(copy.deepcopy(p.meals), body.slot, body.item_index, diet, restr)
    flag_modified(p, "meals")
    db.commit()
    return _out(p)


@router.post("/plans/{pid}/complete-meal")
def complete_meal(pid: int, body: MealCompleteIn, user: User = Depends(require_profile), db: Session = Depends(get_db)):
    p = _own(db, user, pid)
    meals = copy.deepcopy(p.meals)
    meal = next((m for m in meals if m["slot"] == body.slot), None)
    if meal is None:
        raise HTTPException(404, "Meal not found")
    was = meal.get("completed", False)
    meal["completed"] = body.completed
    if body.completed and not was and body.log_to_tracker:
        t = meal["totals"]
        db.add(FoodEntry(user_id=user.id, eaten_on=date.today(), meal=meal["meal_type"], name=meal["name"][:200],
                         quantity_g=sum(i["grams"] for i in meal["items"]) or 1, calories=t["calories"],
                         protein_g=t["protein_g"], carbs_g=t["carbs_g"], fat_g=t["fat_g"], source="meal_plan",
                         source_id=f"plan{p.id}:{meal['slot']}"))
    if not body.completed and was:
        e = db.scalar(select(FoodEntry).where(FoodEntry.user_id == user.id, FoodEntry.source_id == f"plan{p.id}:{meal['slot']}",
                                              FoodEntry.eaten_on == date.today()))
        if e:
            db.delete(e)
    p.meals = meals
    flag_modified(p, "meals")
    db.commit()
    return _out(p)
