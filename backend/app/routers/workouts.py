@router.patch("/sessions/{sid}")
def update_session(sid: int, body: UpdateSessionIn, user: User = Depends(require_profile), db: Session = Depends(get_db)):
    s = db.get(WorkoutSession, sid)
    if not s or s.user_id != user.id:
        raise HTTPException(404, "Session not found")
    if body.exercises is not None:
        s.exercises = body.exercises
    newly_unlocked = []
    if body.status and body.status != s.status:
        s.status = body.status
        if body.status == "completed":
            s.completed_at = utcnow()
            s.duration_minutes = max(1, round((s.completed_at - s.started_at).total_seconds() / 60))
    db.commit()
    if body.status == "completed":
        before = {a["code"] for a in progress_service.evaluate_achievements(db, user) if a["unlocked"] and not a["seen"]}
        newly_unlocked = sorted(before)
    return {**_session_out(s), "new_achievements": newly_unlocked}


@router.get("/sessions")
def history(limit: int = Query(30, le=200), user: User = Depends(require_profile), db: Session = Depends(get_db)):
    rows = db.scalars(select(WorkoutSession).where(WorkoutSession.user_id == user.id, WorkoutSession.status == "completed")
                      .order_by(WorkoutSession.started_at.desc()).limit(limit))
    return [_session_out(s) for s in rows]


