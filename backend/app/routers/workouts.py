log = logging.getLogger("fitai.workouts")


def _plan_out(p: WorkoutPlan) -> dict:
    return {"id": p.id, "title": p.title, "split": p.split, "inputs": p.inputs, "days": p.days,
            "generated_by": p.generated_by, "coach_note": p.coach_note, "is_saved": p.is_saved,
            "rest_days": p.inputs.get("rest_days", []), "recovery_note": p.inputs.get("recovery_note"),
            "created_at": p.created_at.isoformat() + "Z"}


def _session_out(s: WorkoutSession) -> dict:
    return {"id": s.id, "plan_id": s.plan_id, "name": s.name, "started_at": s.started_at.isoformat() + "Z",
            "completed_at": s.completed_at.isoformat() + "Z" if s.completed_at else None,
            "duration_minutes": s.duration_minutes, "exercises": s.exercises, "status": s.status}


def _own_plan(db, user, pid) -> WorkoutPlan:
    p = db.get(WorkoutPlan, pid)
    if not p or p.user_id != user.id:
        raise HTTPException(404, "Workout plan not found")
    return p


@router.post("/generate", status_code=201)
def generate(body: WorkoutPlanIn, user: User = Depends(ai_rate_limit), db: Session = Depends(get_db)):
    prof = user.profile
    if prof is None:
        raise HTTPException(409, "Complete onboarding first")
    goal = body.goal or prof.goal
    exp = body.experience or prof.experience
    days = body.days_per_week or min(prof.workout_days_per_week, 6)
    eq = body.equipment if body.equipment is not None else prof.equipment
    dur = body.duration_minutes or prof.workout_minutes
    plan = wsvc.generate_plan(goal, exp, days, eq, dur, body.split, body.target_muscles, body.recovery)
    note, generated_by, notice = None, "fitai_engine", None
    provider = get_provider(user.ai_provider_pref)
    if body.use_ai and provider.is_real_llm:
        try:
            system, prompt = workout_note_prompt(prof, plan)
            raw_note = json.loads(provider.generate_json(system, prompt)).get("coach_note")
            note = raw_note.strip()[:1500] if isinstance(raw_note, str) and raw_note.strip() else None
            generated_by = f"fitai_engine+llm:{provider.label}"[:100]
        except (ProviderError, json.JSONDecodeError, AttributeError) as e:
            log.warning("AI workout note failed: %s", e)
            notice = "AI coach note unavailable; plan generated by the FitAI engine."
    if not note:
        note = (f"{plan['split_name']} fits {days} training day(s) per week at the {exp} level. Progress by adding 1–2 reps "
                "each session until you reach the top of the rep range, then increase the load slightly. "
                f"{plan['recovery_note']}")
        if body.use_ai and not provider.is_real_llm:
            notice = "Demo mode: coach note written by the rule-based engine (no LLM configured)."
    inputs = {"goal": goal, "experience": exp, "days_per_week": days, "equipment": eq, "duration_minutes": dur,
              "split": body.split, "target_muscles": body.target_muscles, "recovery": body.recovery,
              "rest_days": plan["rest_days"], "recovery_note": plan["recovery_note"]}
    wp = WorkoutPlan(user_id=user.id, title=f"{plan['split_name']} · {days} days/week", split=plan["split"], inputs=inputs,
                     days=plan["days"], generated_by=generated_by, coach_note=note, is_saved=False)
    db.add(wp)
    db.commit()
    return {**_plan_out(wp), "notice": notice}


@router.get("/plans")
def list_plans(user: User = Depends(require_profile), db: Session = Depends(get_db)):
    return [_plan_out(p) for p in db.scalars(select(WorkoutPlan).where(WorkoutPlan.user_id == user.id)
                                             .order_by(WorkoutPlan.id.desc()).limit(30))]


@router.get("/plans/active")
def active_plan(user: User = Depends(require_profile), db: Session = Depends(get_db)):
    p = db.scalar(select(WorkoutPlan).where(WorkoutPlan.user_id == user.id, WorkoutPlan.is_saved.is_(True))
                  .order_by(WorkoutPlan.id.desc())) or \
        db.scalar(select(WorkoutPlan).where(WorkoutPlan.user_id == user.id).order_by(WorkoutPlan.id.desc()))
    return _plan_out(p) if p else None


@router.get("/plans/{pid}")
def get_plan(pid: int, user: User = Depends(require_profile), db: Session = Depends(get_db)):
    return _plan_out(_own_plan(db, user, pid))


@router.post("/plans/{pid}/save")
def save_plan(pid: int, user: User = Depends(require_profile), db: Session = Depends(get_db)):
    p = _own_plan(db, user, pid)
    p.is_saved = True
    db.commit()
    return _plan_out(p)


@router.delete("/plans/{pid}", status_code=204)
def delete_plan(pid: int, user: User = Depends(require_profile), db: Session = Depends(get_db)):
    db.delete(_own_plan(db, user, pid))
    db.commit()


@router.post("/sessions/start", status_code=201)
def start(body: StartWorkoutIn, user: User = Depends(require_profile), db: Session = Depends(get_db)):
    # one active session at a time
    for s in db.scalars(select(WorkoutSession).where(WorkoutSession.user_id == user.id, WorkoutSession.status == "in_progress")):
        s.status = "abandoned"
    if body.plan_id:
        p = _own_plan(db, user, body.plan_id)
        if body.day_index >= len(p.days):
            raise HTTPException(400, "Invalid day")
        day = p.days[body.day_index]
        name, exercises = day["name"], copy.deepcopy(day["exercises"])
    else:
        prof = user.profile
        day = wsvc.generate_plan(prof.goal, prof.experience, 1, prof.equipment, prof.workout_minutes)["days"][0]
        name, exercises = f"Quick {day['name']}", day["exercises"]
    for e in exercises:
        e["completed"] = False
        e["sets_done"] = 0
    s = WorkoutSession(user_id=user.id, plan_id=body.plan_id, name=name, started_at=utcnow(), exercises=exercises,
                       status="in_progress")
    db.add(s)
    db.commit()
    return _session_out(s)


