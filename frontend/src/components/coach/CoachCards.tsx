import clsx from 'clsx'
import { AlertTriangle, ArrowRight, Bookmark, Dumbbell, Flame, Info, LineChart as LineIcon, Salad, Search, TrendingDown, TrendingUp, User, Utensils } from 'lucide-react'
import { useNavigate } from 'react-router-dom'
import { Line, LineChart, ResponsiveContainer, YAxis } from 'recharts'
import type { Card as CardT, Units } from '../../types'
import { fmtWeight } from '../../utils/format'
import { MacroDonut } from '../charts/Charts'
import { MacroRow } from '../ui'

const ICON: Record<string, any> = { metrics: Flame, macros: Salad, weight_trend: LineIcon, workout: Dumbbell, foods: Search, nutrition_day: Utensils, insights: Info, saved: Bookmark, profile: User }

function Shell({ card, children, action }: { card: CardT; children: React.ReactNode; action?: React.ReactNode }) {
  const I = ICON[card.type] ?? Info
  return (
    <div className="animate-fade-up overflow-hidden rounded-2xl border border-line bg-ink-900/80">
      <div className="flex items-center justify-between gap-2 border-b border-line-soft px-4 py-2.5">
        <p className="flex items-center gap-2 text-[13px] font-semibold text-fg"><I className="h-3.5 w-3.5 text-lime" />{card.title}</p>
        {action}
      </div>
      <div className="p-4">{children}</div>
    </div>
  )
}

function Link({ to, label, state }: { to: string; label: string; state?: any }) {
  const nav = useNavigate()
  return <button onClick={() => nav(to, { state })} className="flex items-center gap-1 text-xs font-medium text-lime hover:underline">{label}<ArrowRight className="h-3 w-3" /></button>
}

export function CoachCard({ card, units }: { card: CardT; units: Units }) {
  switch (card.type) {
    case 'metrics':
      return (
        <Shell card={card}>
          <div className="grid grid-cols-2 gap-2 sm:grid-cols-4">
            {card.items.map((i: any) => (
              <div key={i.label} className={clsx('rounded-xl px-3 py-2.5', i.highlight ? 'bg-lime/10 ring-1 ring-lime/30' : 'bg-white/[0.03]')}>
                <p className="text-[11px] text-fg-dim">{i.label}</p>
                <p className={clsx('mt-0.5 text-sm font-semibold tabular-nums', i.highlight ? 'text-lime' : 'text-fg')}>{i.value}</p>
              </div>
            ))}
          </div>
          {card.note && <p className="mt-3 text-xs text-fg-dim">{card.note}</p>}
        </Shell>
      )
    case 'macros':
      return (
        <Shell card={card} action={<Link to="/diet" label="Build meal plan" />}>
          <div className="flex items-center gap-5">
            <MacroDonut protein={card.protein_g} carbs={card.carbs_g} fat={card.fat_g} calories={card.calories} size={110} />
            <div className="grid flex-1 gap-2 text-sm">
              {[['Protein', card.protein_g, '#C6F36B'], ['Carbs', card.carbs_g, '#7CC4F2'], ['Fat', card.fat_g, '#F2B85B']].map(([l, v, c]) => (
                <div key={l as string} className="flex items-center justify-between rounded-lg bg-white/[0.03] px-3 py-1.5"><span className="flex items-center gap-2 text-fg-muted"><span className="h-2 w-2 rounded-full" style={{ background: c as string }} />{l}</span><b className="tabular-nums">{v as number} g</b></div>
              ))}
              <p className="text-[11px] text-fg-dim">Approximate daily targets for {card.calories} kcal</p>
            </div>
          </div>
        </Shell>
      )
    case 'weight_trend': {
      const recs = card.records || []
      const up = (card.trend ?? 0) > 0
      return (
        <Shell card={card} action={<Link to="/progress" label="Open progress" />}>
          {recs.length < 2 ? <p className="text-sm text-fg-muted">Not enough weigh-ins yet.</p> : (
            <div className="flex items-center gap-4">
              <div className="min-w-[120px]">
                <p className="text-[11px] text-fg-dim">Change in window</p>
                <p className="font-display text-2xl font-bold tabular-nums">{card.change_kg > 0 ? '+' : ''}{fmtWeight(card.change_kg, units)}</p>
                {card.trend != null && <p className={clsx('mt-1 flex items-center gap-1 text-xs', up ? 'text-amber' : 'text-moss-400')}>{up ? <TrendingUp className="h-3 w-3" /> : <TrendingDown className="h-3 w-3" />}{card.trend > 0 ? '+' : ''}{card.trend} kg/wk trend</p>}
              </div>
              <div className="h-20 flex-1">
                <ResponsiveContainer><LineChart data={recs}><YAxis hide domain={['dataMin - 0.5', 'dataMax + 0.5']} /><Line dataKey="weight_kg" stroke="#C6F36B" strokeWidth={2} dot={false} /></LineChart></ResponsiveContainer>
              </div>
            </div>
          )}
        </Shell>
      )
    }
    case 'workout':
      return (
        <Shell card={card} action={<Link to="/workouts" label="Open planner" />}>
          <p className="mb-2 text-xs text-fg-dim">~{card.duration_minutes} min · generated by the FitAI programming engine</p>
          <div className="divide-y divide-line-soft">
            {card.exercises.map((e: any, i: number) => (
              <div key={i} className="flex items-center justify-between gap-3 py-2 text-[13px]">
                <div className="flex min-w-0 items-center gap-2.5"><span className="flex h-6 w-6 shrink-0 items-center justify-center rounded-md bg-white/[0.04] text-[11px] text-fg-dim">{i + 1}</span><div className="min-w-0"><p className="truncate font-medium text-fg">{e.name}</p><p className="text-[11px] capitalize text-fg-dim">{e.muscle}</p></div></div>
                <span className="shrink-0 tabular-nums text-fg-muted">{e.sets} × {e.reps} · {e.rest_seconds}s</span>
              </div>
            ))}
          </div>
        </Shell>
      )
    case 'foods':
      return (
        <Shell card={card} action={<Link to="/nutrition" label="Log food" />}>
          {card.warning && <p className="mb-2 flex items-center gap-1.5 text-xs text-amber"><AlertTriangle className="h-3 w-3" />{card.warning}</p>}
          {card.results.length === 0 ? <p className="text-sm text-fg-muted">No matches.</p> : card.results.map((f: any) => (
            <div key={f.id} className="flex items-center justify-between gap-3 border-b border-line-soft py-2 text-[13px] last:border-0">
              <div className="min-w-0"><p className="truncate font-medium">{f.name}</p><p className="text-[11px] text-fg-dim">{f.brand || (f.source === 'reference' ? 'FitAI reference value' : 'Open Food Facts')} · per 100 g</p></div>
              <span className="shrink-0 tabular-nums text-fg-muted">{f.calories_100g} kcal · P {f.protein_100g}g</span>
            </div>
          ))}
        </Shell>
      )
    case 'nutrition_day':
      return (
        <Shell card={card} action={<Link to="/nutrition" label="Open tracker" />}>
          <div className="space-y-2.5">
            <MacroRow label="Calories" value={card.totals.calories} target={card.targets.calories} unit=" kcal" color="#C6F36B" />
            <MacroRow label="Protein" value={card.totals.protein_g} target={card.targets.protein_g} color="#C6F36B" />
            <MacroRow label="Carbs" value={card.totals.carbs_g} target={card.targets.carbs_g} color="#7CC4F2" />
            <MacroRow label="Fat" value={card.totals.fat_g} target={card.targets.fat_g} color="#F2B85B" />
          </div>
        </Shell>
      )
    case 'insights':
      return (
        <Shell card={card} action={<Link to="/progress" label="Full analysis" />}>
          <div className="space-y-2">
            {card.insights.map((i: any) => (
              <div key={i.title} className={clsx('rounded-xl px-3 py-2', i.type === 'warning' || i.type === 'safety' ? 'bg-amber/[0.07]' : 'bg-white/[0.03]')}>
                <p className="text-xs font-semibold text-fg">{i.title}</p><p className="mt-0.5 text-xs leading-relaxed text-fg-muted">{i.text}</p>
              </div>
            ))}
          </div>
        </Shell>
      )
    case 'saved':
      return <Shell card={card}><p className="text-sm text-fg-muted">“{card.text}” is now on your dashboard.</p></Shell>
    default:
      return null
  }
}
